    fun currentLanguage(): ApiDocLanguage = ApiDocLanguage.fromCode(ShowDocSettings.getInstance().state.language)

    fun text(key: String, vararg args: Any): String {
        val template = when (currentLanguage()) {
            ApiDocLanguage.ZH -> zh[key] ?: en[key] ?: key
            ApiDocLanguage.EN -> en[key] ?: zh[key] ?: key
        }
        return args.foldIndexed(template) { index, acc, arg -> acc.replace("{$index}", arg.toString()) }
    }
